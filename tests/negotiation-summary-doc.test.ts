/**
 * Writes docs/negotiation-summary-states.md from the engine, for review (walkthrough brief B5).
 * Runs only with WRITE_DOCS=1 (npx vitest run tests/negotiation-summary-doc.test.ts with the env set).
 */
import { it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { setStep, type StateKey } from './helpers/summaryStates';
import { buildNegotiationSummary } from '@/lib/engines/negotiationSummary';

const STATES: [StateKey, string][] = [
  ['step1', 'Step 1 · round 4 arrives (v4 filed)'],
  ['step2', 'Step 2 · side thread linked, before the clarification'],
  ['step3-loop-in', 'Step 3 · Vikram chose Loop in Ananya'],
  ['step3-send-anyway', 'Step 3 · Vikram chose Send anyway'],
  ['step4', 'Step 4 · v6 signing copy checked'],
  ['step5', 'Step 5 · handover (signed v7)'],
];

it.runIf(process.env.WRITE_DOCS === '1')('writes docs/negotiation-summary-states.md', () => {
  const out: string[] = [
    '# Negotiation so far: expected output by step',
    '',
    'Generated by `tests/negotiation-summary-doc.test.ts` from `buildNegotiationSummary` and the fixtures. The same strings are the golden values in `tests/negotiation-summary.test.ts`. Dates are unshifted (the story anchor, 21 Nov 2026); in the app they move with today\'s date.',
    '',
  ];
  for (const [key, title] of STATES) {
    const s = setStep(key);
    const x = buildNegotiationSummary(s, 'D-CLOUDDESK', s.clock, key === 'step5' ? 'handover' : 'deal');
    out.push(`## ${title}`, '', `**${x.title}** · ${x.asOf}`, '', `${x.headline}  `, `${x.countsLine}`, '');
    for (const g of x.groups) {
      out.push(`**${g.title}**`, '');
      for (const t of g.terms) {
        const bits = [t.text + (t.draftText ? ` · ${t.draftText}` : '')];
        if (t.condition) bits.push(`${t.condition.text} (${t.condition.state.replace('_', ' ')})`);
        if (t.sides) bits.push(t.sides.map((z) => z.text).join(' · '));
        if (t.status) bits.push(t.status);
        if (t.action) bits.push(`[${t.action.label}]`);
        if (t.wordHref) bits.push(`[Open §${t.clauseNo}]`);
        if (t.unchanged) bits.push('folded under "other terms unchanged"');
        out.push(`- ${bits.join(' · ')}`);
      }
      for (const n of g.notes) out.push(`- ${n.text}`);
      out.push('');
    }
    out.push(`Rounds: ${x.rounds.map((r) => `R${r.no} ${r.date}`).join(' ── ')}`, '');
  }
  out.push(
    '## Where the fixtures differ from the brief\'s table',
    '',
    '- **Step 4, service credit.** The brief expects service credit "still open" at step 4. In the fixtures it is agreed: Rohan confirms 10% in the supplier thread in step 2 (or Ananya records a call), so by 19 Nov it is agreed and in v6. The fixture wins: the card lists it under "Agreed and in v6".',
    '- **Step 1, renewal notice.** As the brief expects: v4 moves §14.2 from 30 to 90 days, so renewal notice sits under "Agreed, but v4 says otherwise". Once Ananya sends v5 (which restores 30 days), the latest version is v5 and it moves to "Agreed and in v5".',
    '- **Step 2.** The brief\'s step 2 is reached before the clarification is sent; after Rohan\'s reply (or a recorded call) service credit moves to "Agreed and in v4".',
    '- **Step 5.** Every gap was fixed before signing in the walkthrough, so the handover card has nothing "Unresolved at signature". If a gap is left open (for example with only one correction inserted), it is listed there.',
    '',
  );
  writeFileSync('docs/negotiation-summary-states.md', out.join('\n'));
});
